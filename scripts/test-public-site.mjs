import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fetchTrees } from '../public-site/tree-data.js';
const root = resolve(import.meta.dirname, '..');
const html = await readFile(resolve(root, 'build/site/index.html'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(new Set(ids).size, ids.length, 'HTML IDs must be unique');
assert(!html.includes('flutter_bootstrap'), 'Landing must not preload Flutter');
assert(!html.includes('user-scalable=no'), 'Landing must allow zoom');
assert(!html.includes('name="code"'), 'Access code must not be submitted to the host');
assert.equal((html.match(/<h1\b/g) || []).length, 1);
for (const match of html.matchAll(/(?:src|href|srcset)="(\/site-assets\/[^" ]+)"/g)) await access(resolve(root, 'build/site' + match[1]));
const robots = await readFile(resolve(root, 'build/site/robots.txt'), 'utf8');
assert(robots.startsWith('User-agent:'));
const config = JSON.parse(html.match(/id="public-config">(.*?)<\/script>/s)[1]);
for (const key of ['treeModule', 'leafletJs', 'leafletCss']) await access(resolve(root, 'build/site' + config[key]));
const name = i => `projects/demo/databases/(default)/documents/public_trees/tree${i}`;
const doc = i => ({document:{name:name(i),fields:{status:{stringValue:'verified'},species:{stringValue:'Trembesi'},latitude:{doubleValue:-6.7},longitude:{doubleValue:108.5},condition:{stringValue:i===0?'rawan_tumbang':'sehat'}}}});
const requests = [];
const output = await fetchTrees({projectId:'demo',apiKey:'public-key'}, async (_, options) => {
 const query = JSON.parse(options.body).structuredQuery; requests.push(query);
 assert(!JSON.stringify(query).includes('photoBase64')); assert.equal(query.from[0].collectionId,'public_trees');
 return {ok:true,json:async()=>requests.length===1?Array.from({length:200},(_,i)=>doc(i)):[doc(200)]};
});
assert.equal(output.length,201);
assert.equal(output[0].condition,'rawanTumbang');
assert.equal(requests[1].startAt.before,false);
assert.equal(requests[1].startAt.values[0].referenceValue,name(199));
assert.deepEqual(await fetchTrees({projectId:'demo',apiKey:'public-key'},async()=>({ok:true,json:async()=>[{readTime:'now'}]})), []);
await assert.rejects(()=>fetchTrees({projectId:'demo',apiKey:'public-key'},async()=>({ok:false})), /unavailable/);
console.log('PASS: HTML IDs, assets, zoom, tracking privacy, no Flutter at landing, robots, public fields, pagination, empty and failure cases.');

const manifest = JSON.parse(await readFile(resolve(root, 'build/site/manifest.json'), 'utf8'));
assert.equal(manifest.start_url, '/');
assert.equal(manifest.scope, '/');
for (const icon of manifest.icons) await access(resolve(root, 'build/site', icon.src.split('?')[0]));
await access(resolve(root, 'build/site/favicon-pohon.png'));
await access(resolve(root, 'build/site/icons/Icon-180.png'));
console.log('PASS: public manifest, favicon and app icon paths.');
